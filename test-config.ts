// pronto test config: the app's deno configs for its tests, with the runtime.
//
//   deno run --config plugins/pronto/deno.json --allow-read --allow-write \
//     --allow-run=mise plugins/pronto/test-config.ts <appDir>
//
// Each tests/<name>.app.json the app authors becomes tests/<name>.json, its
// imports joined by the platform's specifiers, each mapped to where mise keeps
// that runtime here: the checkout's tree under mise.local.toml, the pinned
// release otherwise. A check image keeps omnishell at /omnishell, where the
// specifier resolves unmapped, so a check runs under the app's own config
// (builders/bayt.cue) and no pronto of the image's pins. A runtime's tree finds
// another as its checkout sibling (pronto's hybrid-local.ts reaches
// ../omnishell/), so where the two are installed apart the sibling's URL is
// mapped too. The paths are the machine's, so the file is written where the
// tests run, never committed (docs/component-contracts.md#test-configs).

import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { entries, ifMissing } from "./missing.ts";

/** Each platform specifier by the runtime it names: its tree's directory in a
 * checkout and its mise tool. */
export const PLATFORM: Record<string, string> = {
  "/omnishell/": "omnishell",
  "/pronto/": "pronto",
};

const SOURCE = /^(.+)\.app\.json$/;

function fail(msg: string): never {
  console.error(`pronto test-config: ${msg}`);
  Deno.exit(1);
}

async function where(tool: string, appDir: string): Promise<string> {
  const out = await new Deno.Command("mise", { args: ["where", tool], cwd: appDir, stdout: "piped", stderr: "inherit" }).output();
  if (!out.success) fail(`mise does not resolve ${tool} in ${appDir}`);
  return pathToFileURL(new TextDecoder().decode(out.stdout).trim()).href.replace(/\/?$/, "/");
}

/** The configs an app's tests run under, by the path each is written to. */
export async function testConfigs(appDir: string): Promise<Map<string, string>> {
  const sources = (await entries(`${appDir}/tests`)).filter((e) => e.isFile && SOURCE.test(e.name)).map((e) => e.name).sort();
  const configs = new Map<string, string>();
  if (sources.length === 0) return configs;
  const trees: Record<string, string> = Object.fromEntries(await Promise.all(Object.values(PLATFORM).map(async (name) => [name, await where(`github:bonisoft3/${name}`, appDir)])));
  const platform: Record<string, string> = Object.fromEntries(Object.entries(PLATFORM).map(([spec, name]) => [spec, trees[name]]));
  for (const [name, tree] of Object.entries(trees)) {
    for (const [sibling, at] of Object.entries(trees)) {
      const beside = new URL(`../${sibling}/`, tree).href;
      if (sibling !== name && beside !== at) platform[beside] = at;
    }
  }
  for (const name of sources) {
    const config = JSON.parse(await Deno.readTextFile(`${appDir}/tests/${name}`));
    const imports: Record<string, string> = config.imports ?? {};
    const claimed = Object.keys(imports).filter((spec) => spec in PLATFORM);
    if (claimed.length > 0) fail(`tests/${name} maps ${claimed.join(", ")}, which pronto maps to the runtime`);
    const target = `tests/${name.replace(SOURCE, "$1")}.json`;
    const text = JSON.stringify({ ...config, imports: { ...imports, ...platform } }, null, 2);
    configs.set(target, `// generated by pronto from tests/${name} — do not edit\n${text}\n`);
  }
  return configs;
}

if (import.meta.main) {
  const appDir = resolve(Deno.args[0] ?? fail("usage: test-config.ts <appDir>"));
  for (const [rel, text] of await testConfigs(appDir)) {
    if ((await ifMissing(Deno.readTextFile(`${appDir}/${rel}`), null)) !== text) await Deno.writeTextFile(`${appDir}/${rel}`, text);
  }
}
