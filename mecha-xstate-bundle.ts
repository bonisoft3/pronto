import { fileURLToPath } from "node:url";

export async function bundleMechaXState(): Promise<string> {
  const output = await Deno.makeTempFile({ suffix: ".js" });
  try {
    const result = await new Deno.Command(Deno.execPath(), {
      args: ["bundle", "--no-config", "--no-lock", "--platform", "browser", "--format", "cjs", "--minify", fileURLToPath(new URL("mecha-xstate-entry.ts", import.meta.url)), "-o", output],
      stdout: "piped", stderr: "piped",
    }).output();
    if (!result.success) throw Error(new TextDecoder().decode(result.stderr));
    const bundle = (await Deno.readTextFile(output)).trim();
    return `// Generated by mecha-xstate-bundle.ts from pinned XState; do not edit.\n(() => {\nconst console = {log: () => { throw new Error("unexpected XState logger"); }};\nconst module = {exports: {}};\nconst exports = module.exports;\n${bundle}\nreturn module.exports;\n})()\n`;
  } finally { await Deno.remove(output); }
}

if (import.meta.main) await Deno.writeTextFile(new URL("mecha-xstate.js", import.meta.url), await bundleMechaXState());
