import { assertEquals } from "jsr:@std/assert@1.0.11";
import { compileCortexDurable } from "../cortex-durable.ts";
import { terminal } from "../mecha-fixtures.ts";
import { executeMecha } from "../../omnishell/test/mecha-local.ts";
import { batchMachine } from "./machine.ts";
const source = await Deno.readTextFile(new URL("./rules.js",import.meta.url));
const compiled = await compileCortexDurable(batchMachine,source,terminal);
Deno.test("the shipped compute machine is the current Cortex compiler output",async () => {
  assertEquals(await Deno.readTextFile(new URL("../../../libraries/mecha/services/compute/batch-machine.sql",import.meta.url)),
    "-- Generated by Pronto compute/generate.ts; edit the Cortex machine source.\n"+compiled.sql);
});
Deno.test("claiming freezes a revision while new invalidations survive publication",async () => {
  const run = (input: unknown) => executeMecha(compiled.source,batchMachine.machine.fuel,input) as Promise<{kind: string; state: {phase: string; requested: number; completed: number; wake: number; claimed: number; due: number}}>;
  const context = {tier:"mecha",actor:null,now:500};
  let {state} = await run({initialize:true,payload:{name:"ratings",coalesce:1000,attempts:25,revision:0},context,viewers:[]});
  for (const kind of ["invalidate","schedule","claim","invalidate","complete"]) {
    const answer = await run({state,event:{kind,payload:{}},context,viewers:[]});
    assertEquals(answer.kind,"accepted");
    state=answer.state;
  }
  assertEquals([state.phase,state.requested,state.completed,state.wake,state.claimed],["idle",2,1,0,0]);
  const next = await run({state,event:{kind:"schedule",payload:{}},context,viewers:[]});
  assertEquals([next.state.wake,next.state.due],[2,1500]);
});
