import { compileCortexDurable } from "../cortex-durable.ts";
import { instrument } from "../../omnishell/instrument.ts";
import { batchMachine } from "./machine.ts";
const rules = await Deno.readTextFile(new URL("./rules.js", import.meta.url));
const terminal = { instrument, ses: await Deno.readTextFile(new URL("../../omnishell/interpreter/vendor/ses.umd.min.js", import.meta.url)) };
const compiled = await compileCortexDurable(batchMachine, rules, terminal);
const destination = Deno.args[0];
if (!destination) throw new Error("provide the generated batch-machine.sql destination");
await Deno.writeTextFile(destination, "-- Generated by Pronto compute/generate.ts; edit the Cortex machine source.\n" + compiled.sql);
