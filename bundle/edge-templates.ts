const declaration = '{{- $o := placeholder "http.vars.origin" -}}'
const origin = 'https://pronto-origin.invalid'
const documentHeader = '<!-- generated by pronto from program.cue — do not edit -->\n'
const declared = (text: string) => text.startsWith(declaration + '\n') || text.startsWith(documentHeader + declaration + '\n')

/** Undo Caddy's literal escaping before release addressing hashes inline scripts. */
export function prepareEdgeTemplate(text: string): string {
  if (!declared(text)) return text
  if (text.includes(origin)) throw new Error(`edge template contains reserved origin ${origin}`)
  const prepared = text.replaceAll('{{$o}}', origin)
  return text.startsWith(documentHeader) ? prepared.replaceAll('{{"{{"}}', '{{') : prepared
}

type Assets = { fetch(request: Request): Promise<Response> }

/** These templates vary only with the deployment's origin, so their file
 * validators remain valid, as they do behind the container's Caddy door. */
export function originAssets(assets: Assets): Assets {
  return {
    async fetch(request) {
      const response = await assets.fetch(request)
      if (response.status !== 200 || !/^(text\/(html|plain|xml)|application\/xml)(;|$)/i.test(response.headers.get('content-type') ?? '')) return response
      if (request.method === 'HEAD') {
        const result = new Response(null, response)
        result.headers.delete('content-length')
        return result
      }
      const text = await response.clone().text()
      if (!declared(text)) return response
      await response.body?.cancel()
      const result = new Response(text.replace(declaration + '\n', '').replaceAll(origin, new URL(request.url).origin), response)
      result.headers.delete('content-length')
      result.headers.delete('content-encoding')
      return result
    },
  }
}
