import assert from 'node:assert/strict'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'
import { writeEdgeAssets } from './edge-assets.ts'
import { addressEdgeAssets, releaseAddresses } from './edge-addresses.ts'
import { originAssets, prepareEdgeTemplate } from './edge-templates.ts'

const declaration = '{{- $o := placeholder "http.vars.origin" -}}'

Deno.test('edge documents bind request origins after addressing without changing inline script hashes', async () => {
  const directory = await Deno.makeTempDir({ prefix: 'edge-templates-' })
  const app = path.join(directory, 'app'), terminal = path.join(directory, 'terminal'), out = path.join(directory, 'public')
  const inline = 'globalThis.literal = "{{ example }}";'
  const html = `<html><head><meta http-equiv="Content-Security-Policy" content="script-src 'self'"><base href="/shell/"></head><body><script type="module" src="./boot.js"></script></body></html>`
  try {
    const files: Record<string, string> = {
      'shell/index.html': html,
      'shell/boot.js': 'export const boot = true;',
      'shell/shell.json': JSON.stringify({ routes: [] }),
      'documents/regras/index.html': `<!-- generated by pronto from program.cue — do not edit -->\n${declaration}\n` + html.replace('</head>', '<link rel="canonical" href="{{$o}}/regras"><link rel="alternate" href="{{$o}}/ar/reglas"></head>').replace('</body>', `<script>${inline.replaceAll('{{', '{{"{{"}}')}</script></body>`),
      'robots.txt': `${declaration}\nSitemap: {{$o}}/sitemap.xml\n`,
      'sitemap.xml': `${declaration}\n<?xml version="1.0"?><urlset><loc>{{$o}}/regras</loc></urlset>`,
    }
    for (const [name, text] of Object.entries(files)) {
      await Deno.mkdir(path.dirname(path.join(app, name)), { recursive: true })
      await Deno.writeTextFile(path.join(app, name), text)
    }
    await writeEdgeAssets(app, terminal, out, Object.keys(files).map(file => ({ file, target: '/srv/' + file.replace('documents/', '') })))
    const addresses = await releaseAddresses(fileURLToPath(new URL('../../omnishell', import.meta.url)))
    await addressEdgeAssets(addresses, out, { iceServers: [] })
    const built = await Deno.readTextFile(path.join(out, 'regras/index.html'))
    const asset = originAssets({ fetch: () => Promise.resolve(new Response(built, { headers: { 'content-type': 'text/html', etag: '"source"', 'cache-control': 'public, max-age=0, must-revalidate', 'content-length': String(built.length) } })) })
    for (const host of ['https://truco.example', 'http://localhost:8787']) {
      const response = await asset.fetch(new Request(host + '/regras?language=pt'))
      const served = await response.text()
      assert.ok(served.includes(`href="${host}/regras"`))
      assert.ok(served.includes(`href="${host}/ar/reglas"`))
      assert.ok(!served.includes(declaration))
      assert.ok(!served.includes('pronto-origin.invalid'))
      assert.ok(served.includes(inline))
      for (const [, script] of served.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
        const hash = btoa(String.fromCharCode(...new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(script)))))
        assert.ok(served.includes(`'sha256-${hash}'`), 'the served inline bytes must remain authorized by the addressed policy')
      }
      assert.equal(response.headers.get('etag'), '"source"')
      assert.equal(response.headers.get('cache-control'), 'public, max-age=0, must-revalidate')
      assert.equal(response.headers.get('content-length'), null)
    }
    for (const [name, contentType] of [['robots.txt', 'text/plain'], ['sitemap.xml', 'application/xml']]) {
      const body = await Deno.readTextFile(path.join(out, name))
      const assets = originAssets({ fetch: () => Promise.resolve(new Response(body, { headers: { 'content-type': contentType } })) })
      const rendered = await (await assets.fetch(new Request(`https://site.example:8443/${name}`))).text()
      assert.ok(rendered.includes('https://site.example:8443/'))
      assert.ok(!rendered.includes('{{'))
      if (name === 'sitemap.xml') assert.ok(rendered.startsWith('<?xml'))
    }
  } finally { await Deno.remove(directory, { recursive: true }) }
})

Deno.test('edge template binding preserves literals, non-templates, validators, HEAD, and errors', async () => {
  const literal = '<p>{{- $o := placeholder "http.vars.origin" -}}</p>'
  assert.equal(prepareEdgeTemplate(literal), literal)
  const header = '<!-- generated by pronto from program.cue — do not edit -->\n'
  const prepared = prepareEdgeTemplate(`${header}${declaration}\n<a href="{{$o}}/regras">{{"{{"}}$o}}</a>`)
  const rendered = await originAssets({ fetch: () => Promise.resolve(new Response(prepared, { headers: { 'content-type': 'text/html' } })) }).fetch(new Request('https://site.example/regras'))
  assert.equal(await rendered.text(), header + '<a href="https://site.example/regras">{{$o}}</a>')
  for (const response of [new Response(null, { status: 304, headers: { etag: '"source"' } }), new Response('missing', { status: 404 }), new Response(declaration, { headers: { 'content-type': 'application/javascript' } })]) {
    assert.equal(await originAssets({ fetch: () => Promise.resolve(response) }).fetch(new Request('https://site.example/regras')), response)
  }
  const head = await originAssets({ fetch: () => Promise.resolve(new Response(null, { headers: { 'content-type': 'text/html', 'content-length': '999', etag: '"source"' } })) }).fetch(new Request('https://site.example/regras', { method: 'HEAD' }))
  assert.equal(await head.text(), '')
  assert.equal(head.headers.get('content-length'), null)
  assert.equal(head.headers.get('etag'), '"source"')
})
