// ir.md, ir.html as Markdown (ir-md.ts): the author's prose and pronto's cards both, each design
// object's anchor kept, and nothing of the page that is not the document.
import { assertEquals, assertStringIncludes } from "jsr:@std/assert@1.0.11";
import { irMarkdown } from "./ir-md.ts";

const IR = `<!doctype html><html><head><meta charset="utf-8"><title>x</title><style>p{}</style></head><body>
<h1>Shop — IR</h1>
<p>Orders, kept on the <b>server</b> &amp; read by <a href="#Order">Order</a>; see <code>a|b</code>.</p>
<section id="Order" data-kind="entity" data-durability="server">
<h3>Order</h3>
<!-- pronto:card --><div class="card"><header class="ehead"><span class="chips"><span class="chip"><b>durability</b> server</span><span class="chip"><b>level</b> 4</span></span><span class="counts">2 fields</span></header>
<div class="names"><span class="lbl">fields</span><span class="namelist"><span class="fname">id<i class="m">pk</i></span><span class="fname">total</span></span></div>
<details class="more"><summary>all fields</summary><table class="fields"><tr><td>1</td><td>id</td><td>a|b</td></tr></table></details>
<details class="more json"><summary>the entity, as JSON</summary><div class="jt"><div class="jl"><span class="jk">name</span>: <span class="jv">&quot;Order&quot;</span></div><details class="jn"><summary><span class="jk">fields</span> <span class="jv">[1]</span></summary><div class="jl"><span class="jk">0</span>: <span class="jv">&quot;id&quot;</span></div></details></div></details>
</div><!-- /pronto:card -->
<p>An order, as the author describes it.</p>
<ul><li>one</li><li>two <i>items</i></li></ul>
</section>
<pre class="mermaid">flowchart LR
  a --> b</pre>
<figure id="list-empty" data-kind="state" data-of="list"><svg viewBox="0 0 1 1"><text>drawn</text></svg><figcaption>No orders yet.</figcaption></figure>
<script type="application/json" data-kind="paths" data-of="list">{"buy": {"states": ["empty"]}}</script>
<script>console.log("not the document")</script>
<table><thead><tr><th>a</th><th>b</th></tr></thead><tbody><tr><td>1</td><td>2</td></tr></tbody></table>
</body></html>`;

Deno.test("the prose reads as Markdown, its inline marks and links kept", () => {
  const md = irMarkdown(IR);
  assertEquals(md.split("\n")[0], "<!-- generated by pronto from ir.html: do not edit, edit ir.html -->");
  assertStringIncludes(md, "# Shop — IR\n\nOrders, kept on the **server** & read by [Order](#Order); see `a|b`.");
  assertStringIncludes(md, "An order, as the author describes it.");
  assertStringIncludes(md, "- one\n- two *items*");
  assertEquals(/<style|p\{\}|console\.log|<svg|<span|<div/.test(md), false, "nothing of the page that is not the document");
});

Deno.test("a design object keeps its anchor and kind, so ir.md#Order lands where ir.html#Order does", () => {
  const md = irMarkdown(IR);
  assertStringIncludes(md, '<a id="Order"></a>\n<!-- entity -->\n\n### Order');
  assertStringIncludes(md, '<a id="list-empty"></a>\n<!-- state of list -->');
});

Deno.test("a card reads as its chips on a line, its labels named, its JSON indented", () => {
  const md = irMarkdown(IR);
  assertStringIncludes(md, "**durability** server · **level** 4 — 2 fields");
  assertStringIncludes(md, "**fields**: id*pk*, total");
  assertStringIncludes(md, "<details><summary>all fields</summary>\n\n|  |  |  |\n| --- | --- | --- |\n| 1 | id | a\\|b |\n\n</details>");
  assertStringIncludes(md, '```\nname: "Order"\nfields [1]\n  0: "id"\n```');
});

Deno.test("mermaid stays a diagram, a drawn picture its caption and a link, a screen's paths JSON", () => {
  const md = irMarkdown(IR);
  assertStringIncludes(md, "```mermaid\nflowchart LR\n  a --> b\n```");
  assertStringIncludes(md, "*No orders yet.* (drawn in [ir.html](ir.html#list-empty))");
  assertStringIncludes(md, '*paths of list:*\n\n```json\n{\n  "buy": {');
  assertStringIncludes(md, "| a | b |\n| --- | --- |\n| 1 | 2 |");
});
